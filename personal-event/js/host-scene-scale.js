/*
  host-scene-scale.js
  控制「1200x1200 陰影合成面板」按下【確認並匯出到主持人圖層】之後，
  這張合成好的圖，廣播成主持人圖片套用到各版位時，第一次自動貼合的大小要再縮放多少、
  額外要往下/往上偏移幾個 px。

  跟 shadow-scene-scale.js 的差異：
    shadow-scene-scale.js → 管的是陰影面板編輯中，即時廣播預覽（host1/host2/product
                              個別素材）套用到各版位畫布時的縮放，跟主持人圖層無關。
    這份 host-scene-scale.js → 管的是按下「確認並匯出到主持人圖層」之後，
                              合成完的那張圖被當成一般主持人圖片時，各版位的預設縮放/偏移。

  只影響「圖片第一次被送進這個版位、自動貼合作圖區」那一次的大小／位置
  （initHostPos 裡『有色部分填滿作圖區、再放大 20%』算出來的結果，再乘上/加上這裡的數字）。
  貼合完之後使用者在畫布上手動拖曳/縮放調整過，就照使用者調整的結果，
  不會被這裡的倍率蓋掉——跟原本單一主持人照片的操作方式完全一樣。

  ── 用法：每個版位可以是「純數字」或「物件」二選一 ──
    純數字：例如 '05_fb_post': 80，這個版位不管目前是哪個版型（A/B/C）都用同一個數字。
    物件：例如 '04_ig': { _default: 0.82, C: 0.75 }
      → C 版型用 0.75，其他版型（A/B）都退回 _default 的 0.82。
      → 不用三個版型都填，只列出想特別調整的版型就好，沒列出的版型自動退回 _default。
    兩種寫法可以每個版位各自選，互不影響（想全部版型共用就用純數字，
    想依版型細分就用物件），未來哪個版位需要再拆分依版型設定，直接把那一行改成物件寫法即可。

  _default（最外層）：完全沒列出的版位，都用這個數字（純數字，所有版型共用）。

  版位 id 怎麼來：自動抓網址檔名（例如 01_thumbnail.html → '01_thumbnail'），
  跟專案裡其他設定檔（shadow-scene-scale / logo-row-defaults 等）用同一套規則。
*/
window.HostSceneScale = {

  _default: 1,

  /* C 組合（3品，2026-07更新前叫D組合）的合成圖是「寬扁型」（商品左右散開），
     跟主持人「瘦高型」的合成圖形狀差很多，同一個「填滿作圖區」公式套上去會算出
     明顯偏大的倍率，所以額外幫 C 組合加一個縮小倍率，讓視覺份量跟主持人版本
     一致（實際算法見對話紀錄，用真正的匯出合成圖量出來的，不是隨便估的，
     但還是建議實際看過再微調）。 */
  '02_lpbn':      { _default: 1.1,    C: 0.6745 }, // C 再縮小 5%（0.71 → 0.6745）
  '04_ig':        { _default: 0.82, C: 0.783 },  // C 再縮小 10%（0.87 → 0.783）
  '05_fb_post':   { _default: 0.82, C: 0.7068 }, // C 再縮小 7%（0.76 → 0.7068）
  '06_opening':   { _default: 0.9,  C: 0.7125 }, // C 再縮小 5%（0.75 → 0.7125）
  '07_msbn':      { _default: 1, B: 1, C: 0.7 },   // A（純2人）維持原尺寸；B/C 只要畫面裡有商品，就整體縮小到 70%，避免商品被 CTA 蓋到（原本C是因為「寬扁形狀」才縮小到 0.85，這次直接併入新的 0.7 規則，不再疊加計算）
  '08_sbn':       { _default: 0.87, },

  /* ↓ 想依版型細分的話，把某個版位改成物件寫法，比照這樣寫：
  '04_ig': { _default: 0.82, C: 0.75 },  // C 版型另外用 0.75，其他版型維持 0.82
  */

};

/*
  HostSceneOffsetY
  同一張「主持人圖層」合成圖，第一次自動貼合時，額外要往下（正值）／往上（負值）
  再偏移幾個 px。跟 HostSceneScale 一樣，只影響第一次自動貼合的位置，
  使用者手動拖曳調整過之後不會被蓋掉；也一樣可以每個版位選「純數字」或「依版型細分的物件」。

  找不到對應版位就當作 0（不偏移）。
*/
window.HostSceneOffsetY = {

  _default: 0,

  '02_lpbn': 23,
  '04_ig': 40,
  '05_fb_post': 80,
  '06_opening': 40,
  '07_msbn': { _default: 0, B: 2, C: -10 }, // 有商品的組合整體再往上移，跟左邊的縮小70%搭配，讓商品離右下角CTA更遠──實際夠不夠麻煩幫忙預覽確認，這些是先抓的估計值
  '08_sbn':  { _default: 80, },

  /* ↓ 依版型細分寫法比照 HostSceneScale：
  '04_ig': { _default: 40, C: 60 },
  */

};
